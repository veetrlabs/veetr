import { mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../dist/firmware/', import.meta.url);
const headers = { 'User-Agent': 'Veetr-release-mirror', ...(process.env.GITHUB_TOKEN ? { Authorization: `Bearer ${process.env.GITHUB_TOKEN}` } : {}) };
const response = await fetch('https://api.github.com/repos/veetrlabs/veetr/releases/latest', { headers });
if (!response.ok) throw new Error(`Release metadata: HTTP ${response.status}`);
const release = await response.json();
if (!/^\d+\.\d+\.\d+$/.test(release.tag_name)) throw new Error('Unsupported release version');
const name = `veetr-${release.tag_name}.bin`;
const asset = release.assets.find(a => a.name === name);
if (!asset?.digest?.startsWith('sha256:')) throw new Error('Firmware asset or checksum missing');
const binary = await fetch(asset.browser_download_url);
if (!binary.ok) throw new Error(`Firmware download: HTTP ${binary.status}`);
const bytes = Buffer.from(await binary.arrayBuffer());
if (bytes.length !== asset.size || bytes[0] !== 0xe9 || `sha256:${createHash('sha256').update(bytes).digest('hex')}` !== asset.digest) throw new Error('Firmware validation failed');
await mkdir(root, {recursive:true});
await writeFile(new URL(name, root), bytes);
await writeFile(new URL('latest.json', root), JSON.stringify(release));
console.log(`Verified and mirrored ${name}: ${bytes.length} bytes`);
