import React from 'react';
import {render,fireEvent,act} from '@testing-library/react-native';
import PolarDiagram from '../PolarDiagram';
import {polarWindColor,polarWindSpeeds} from '../../../../packages/shared/src/polar/diagram';
jest.mock('react-native',()=>({Text:'Text',View:'View',Pressable:({children,...props}:any)=>require('react').createElement('View',{accessible:true,...props},children),StyleSheet:{flatten:(s:unknown)=>s}}));
jest.mock('react-native-svg',()=>({__esModule:true,default:'Svg',Circle:'Circle',Line:'Line',Path:'Path',Text:'SvgText'}));
jest.mock('../../context/ThemeContext',()=>({useTheme:()=>({theme:'light'})}));
jest.mock('../../i18n',()=>({t:(s:string)=>s,formatNumber:(n:number)=>String(n)}));
const polar={id:'p',name:'Boat',source:'orc' as const,version:'1',createdAt:'2026-10-13T00:00:00Z',points:[6,10,24].flatMap(tws=>[{tws,twa:40,speed:tws/3},{tws,twa:140,speed:tws/2}])};
test('all winds start visible; checkbox tags hide and restore matching reference and measured curves',()=>{
 const screen=render(<PolarDiagram polar={polar} measured={{...polar,id:'measured',source:'learned'}}/>);
 expect(screen.getAllByRole('checkbox')).toHaveLength(3);
 expect(screen.getAllByRole('checkbox').every(x=>x.props.accessibilityState.checked)).toBe(true);
 const paths=()=>screen.UNSAFE_getAllByType('Path' as any);
 expect(paths()).toHaveLength(6);
 expect(paths().filter(p=>p.props.strokeDasharray)).toHaveLength(3);
 const blue=polarWindColor(6,[6,10,24]),red=polarWindColor(24,[6,10,24]);
 expect(blue).toBe('hsl(240, 80%, 48%)');expect(red).toBe('hsl(0, 80%, 48%)');
 fireEvent.press(screen.getByRole('checkbox',{name:'10 kn'}));
 expect(paths()).toHaveLength(4);
 expect(paths().map(p=>p.props.stroke)).toEqual([blue,red,blue,red]);
 fireEvent.press(screen.getByRole('checkbox',{name:'6 kn'}));
 fireEvent.press(screen.getByRole('checkbox',{name:'24 kn'}));
 expect(screen.getByText('Select a wind speed to show its curve.')).toBeTruthy();
 fireEvent.press(screen.getByRole('checkbox',{name:'10 kn'}));
 expect(paths()).toHaveLength(2);
});
test('wind speeds include measured coverage, sort numerically and do not invent source rows',()=>{
 expect(polarWindSpeeds(polar,{...polar,points:[{tws:8,twa:90,speed:4}]})).toEqual([6,8,10,24]);
 expect(polarWindSpeeds({...polar,points:[{tws:6,twa:90,speed:4}]})).toEqual([6]);
 expect(polarWindColor(6,[6])).toBe('hsl(240, 80%, 48%)');
});

test('pinching and dragging stay inside the chart and cancelled gestures release ownership',()=>{
 const interaction=jest.fn(),screen=render(<PolarDiagram polar={polar} onInteractionChange={interaction}/>);
 const svg=()=>screen.UNSAFE_getByType('Svg' as any),surface=()=>screen.getByTestId('polar-gesture-surface');
 const root=screen.UNSAFE_getAllByType('View' as any).find(view=>view.props.onLayout)!;
 fireEvent(root,'layout',{nativeEvent:{layout:{width:320}}});
 const touch=(points:number[][])=>({nativeEvent:{touches:points.map(([pageX,pageY])=>({pageX,pageY}))}});
 expect(surface().props.onStartShouldSetResponder(touch([[100,100]]))).toBe(false);
 expect(surface().props.onStartShouldSetResponder(touch([[100,160],[220,160]]))).toBe(true);
 act(()=>surface().props.onResponderGrant(touch([[100,160],[220,160]])));
 act(()=>surface().props.onResponderMove(touch([[40,160],[280,160]])));
 expect(svg().props.viewBox).toBe('80 80 160 160');
 expect(surface().props.onResponderTerminationRequest()).toBe(false);
 act(()=>surface().props.onResponderRelease());expect(surface().props.onResponderTerminationRequest()).toBe(true);
 act(()=>surface().props.onResponderGrant(touch([[160,160]])));
 act(()=>surface().props.onResponderMove(touch([[200,180]])));
 expect(svg().props.viewBox).toBe('60 70 160 160');
 act(()=>surface().props.onTouchCancel());
 expect(interaction).toHaveBeenLastCalledWith(false);expect(surface().props.onResponderTerminationRequest()).toBe(true);
 act(()=>surface().props.onResponderMove(touch([[300,300]])));
 expect(svg().props.viewBox).toBe('60 70 160 160');
 act(()=>surface().props.onResponderGrant(touch([[160,160]])));act(()=>surface().props.onResponderRelease());
 act(()=>surface().props.onResponderGrant(touch([[160,160]])));act(()=>surface().props.onResponderEnd(touch([])));
 act(()=>surface().props.onResponderRelease());
 expect(svg().props.viewBox).toBe('0 0 320 320');
 expect(surface().props.onStartShouldSetResponder(touch([[100,100]]))).toBe(false);
 expect(screen.queryByRole('button',{name:'Zoom in'})).toBeNull();
 fireEvent(root,'layout',{nativeEvent:{layout:{width:620}}});expect(svg().props.height).toBe(620);
});
